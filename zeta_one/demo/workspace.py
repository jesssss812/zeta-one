"""Payment review workspace on an isolated real gateway. All execution is simulated."""
import base64
import logging
import random
import secrets
import sqlite3
from datetime import timedelta
from typing import Any

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from fastapi.testclient import TestClient

from zeta_one.demo.recipes import RECIPES, VERSION, prepare
from zeta_one.gateway.app import create_app
from zeta_one.gateway.ledger import Ledger
from zeta_one.gateway.scenarios import load_fixture
from zeta_one.gateway.service import Gateway
from zeta_one.gateway.wiring import configuration_from_env, engine_version, real_stages
from zeta_one.identity.signing import sign
from zeta_one.review.explain import summary
from zeta_one.rho.seed import SEED_NOW
from zeta_one.rho.snapshot import Store
from zeta_one.rho import mutations
from zeta_one.contracts import SetupOp

LOG = logging.getLogger("zeta_one.workspace")
PATH = "/v1/actions/propose_payment"
PROVENANCE = f"Synthetic data generated by {VERSION}; fresh real gateway assessment."


class _ModelsOff:
    class messages:
        @staticmethod
        def create(**kwargs):
            raise RuntimeError("Models disabled: gathered evidence only")


class Workspace:
    def __init__(self, live_models: bool = False, review_client: Any = None):
        self.live_models = live_models
        self._connection = sqlite3.connect(":memory:", check_same_thread=False)
        self._connection.row_factory = sqlite3.Row
        self._store = Store()
        # With models on, the configuration ZETA_RISK_CONFIGURATION names (engineered by default, or
        # jev, which puts Jev before Opus); with models off, the rules alone.
        config = configuration_from_env()
        if not live_models:
            config = config.model_copy(update={"tiers": ["tier0"], "escalation": "none"})
        self._clock = SEED_NOW
        self.gateway = Gateway(stages=real_stages(self._connection, self._store, configuration=config),
            ledger=Ledger(self._connection), clock=lambda: self._clock, version=engine_version())
        self.gateway.review_client = review_client if live_models else _ModelsOff()
        self._token = secrets.token_urlsafe(24)
        self._admin = {"Authorization": f"Bearer {self._token}"}
        self._client = TestClient(create_app(self.gateway, self._token))
        fixture = load_fixture("routine_bill_payment")
        identity = fixture.decision_record.identity
        self._agent, self._base = identity.claimed_agent_id, fixture.proposal
        self._key = Ed25519PrivateKey.generate()
        self._post("/v1/agents", {"agent_id": self._agent, "business_id": identity.business_id,
            "owner": "Synthetic AP owner", "public_key": base64.b64encode(self._key.public_key().public_bytes_raw()).decode()})
        self._post("/v1/authorizations", fixture.decision_record.authorization.snapshot)
        self._payments: list[dict] = []
        self.selected_id = None
        self._index = 0
        self._challenges = {}

    def close(self):
        self._client.close()
        self._connection.close()
        self._store.close()

    def _post(self, path, payload):
        response = self._client.post(path, json=payload, headers=self._admin)
        if response.status_code >= 400:
            raise ValueError(response.json())
        return response.json()

    def _propose(self, proposal):
        self._clock += timedelta(seconds=1)
        body = proposal.model_dump_json().encode()
        response = self._client.post(PATH, content=body, headers=sign(self._key, self._agent, "POST", PATH, body, self._clock))
        if response.status_code >= 400:
            raise ValueError(response.json())
        answer = response.json()
        self._challenges[answer["decision_id"]] = answer.get("challenge_id")
        return answer["decision_id"]

    def state(self):
        payments = []
        for payment in self._payments:
            record = self.gateway.ledger.decision(payment["id"])
            payments.append({k: v for k, v in payment.items() if k != "_proposal"} | {"record": record, "summary": summary(record)})
        return {"mode": "live" if self.live_models else "rules", "recipes": RECIPES,
            "payments": payments, "selected_id": self.selected_id, "provenance": PROVENANCE}

    def act(self, action: str, payload: dict | None = None):
        payload = payload or {}
        if action == "reset":
            live, client = self.live_models, self.gateway.review_client
            self.close()
            self.__init__(live, client)
            return self.state()
        if action in ("add", "random"):
            recipe_id = random.choice(RECIPES)["id"] if action == "random" else payload.get("recipe_id")
            seed = payload.get("seed")
            if action == "random":
                seed = random.randrange(2 ** 31)
            if seed is not None and (not isinstance(seed, int) or isinstance(seed, bool)):
                raise ValueError("seed must be an integer")
            self._index += 1
            proposal = prepare(self._store, recipe_id, self._index, self._base, seed)
            title = next(r["title"] for r in RECIPES if r["id"] == recipe_id)
            LOG.info("workspace: new payment, %s (recipe %s, seed %s)", title, recipe_id,
                     seed if seed is not None else "fixed defaults")
            if recipe_id == "blocked-destination":
                prior = self._propose(proposal)
                self._post(f"/v1/decisions/{prior}/outcomes", {"finding": "payee_fraud", "verification": "bank_confirmation",
                    "by": "Synthetic bank reviewer", "note": "Synthetic setup: bank confirmed the destination is not the vendor's."})
            decision_id = self._propose(proposal)
            recipe = next(r for r in RECIPES if r["id"] == recipe_id)
            self._payments.append({"id": decision_id, "recipe_id": recipe_id, "title": recipe["title"],
                "case_file": None, "events": [{"title": "Payment assessed", "detail": "Real gateway decision."}],
                "provenance": PROVENANCE + f" Recipe: {recipe_id}; seed: {seed if seed is not None else 'fixed defaults' }.", "_proposal": proposal})
            self.selected_id = decision_id
            return self.state()
        payment = next((p for p in self._payments if p["id"] == payload.get("id")), None)
        if payment is None:
            raise ValueError("unknown payment")
        decision_id = payment["id"]
        LOG.info("workspace: %s on %s", action, payment["title"])
        if action == "assemble":
            payment["case_file"] = self._post("/v1/cases", {"decision_id": decision_id, "by": "Workspace reviewer"})
            detail = "Case assistant invoked." if self.live_models else "Models disabled; evidence gathered without a model."
        elif action == "outcome":
            self._post(f"/v1/decisions/{decision_id}/outcomes", {k: payload[k] for k in ("finding", "verification", "note") if k in payload} | {"by": "Workspace reviewer"})
            detail = "Human finding recorded with its verification provenance."
        elif action == "resolve":
            challenge = self._challenges.get(decision_id)
            if not challenge:
                raise ValueError("payment has no challenge to resolve")
            self._post(f"/v1/challenges/{challenge}/resolve", {k: payload[k] for k in ("outcome", "finding", "verification", "note") if k in payload} | {"by": "Workspace reviewer"})
            detail = f"Human resolution: {payload.get('outcome')}."
        elif action == "repeat":
            previous = payment["_proposal"]
            self._index += 1
            bill_id = f"bill_workspace_followup_{self._index}"
            mutations.apply(self._store, SetupOp(op="add_bill", args={"bill_id": bill_id,
                "counterparty_id": previous.counterparty_id, "amount": previous.amount.model_dump(),
                "document_text": f"Follow-up invoice WS-{self._index}. Services provided. Total ${previous.amount.amount / 100:,.2f}."}))
            proposal = previous.model_copy(update={"bill_id": bill_id, "source_document_ids": [bill_id]})
            new_id = self._propose(proposal)
            self._payments.append({**payment, "id": new_id, "case_file": None,
                "events": [{"title": "Payment repeated", "detail": f"Fresh matching successor invoice after {decision_id}; same destination and amount."}], "_proposal": proposal})
            self.selected_id = new_id
            return self.state()
        else:
            raise ValueError("unknown workspace action")
        payment["events"].append({"title": action.capitalize(), "detail": detail})
        self.selected_id = decision_id
        return self.state()


def export_state(recipe_ids=None):
    workspace = Workspace()
    try:
        for recipe_id in recipe_ids or [r["id"] for r in RECIPES]:
            workspace.act("add", {"recipe_id": recipe_id})
        return workspace.state()
    finally:
        workspace.close()


async def export_preview():
    return export_state()
